const assert=require('node:assert/strict');
const {product,totals,shipping}=require('node:vm').runInNewContext(require('node:fs').readFileSync(new URL('../public/store/commerce.js','file://'+__filename),'utf8')+';module.exports',{module:{exports:{}}});
const item=[{size:'M',quantity:1}];
assert.equal(product.priceCents,7500);
assert.equal(Object.hasOwn(product,'stockTotal'),false);
assert.equal(totals(item).totalCents,null);
assert.equal(totals(item,'home').totalCents,8350);
assert.equal(totals(item,'relay').totalCents,7990);
assert.equal(totals([{size:'M',quantity:2}],'home').totalCents,null);
assert.equal(totals(item,'unknown').totalCents,null);
assert.equal(totals(item,'home').estimate,true);
assert.equal(totals([], 'home').totalCents,null);
assert.equal(shipping.relay.priceCents,490);
assert.equal(shipping.home.priceCents,850);
assert.equal(product.sizes.join(','),'S,M,L');
assert.equal(Object.hasOwn(product,'stock'),false);
